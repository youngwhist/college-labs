    ("F-07", "Уведомления о сроке возврата (e-mail, за 2 дня)", "S", ["О", "+", "", "−", ""]),
    ("F-08", "Отчёты: популярные книги, должники, движение фонда", "C", ["О", "", "", "−", "+"]),
    ("U-01", "Выдача книги библиотекарем — не более 3 действий", "M", ["+", "О", "", "+", ""]),
    ("U-02", "Освоение системы новым библиотекарем — не дольше 1 часа", "S", ["", "О", "", "", "+"]),
